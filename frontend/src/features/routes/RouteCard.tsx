import type { IntervalMi, PlanRoute } from '../../lib/api/types'
import { formatAvgRisk, formatDuration, formatMiles, formatTime } from '../../lib/format/format'
import type { MapRoute } from '../../lib/plan/decodePlan'
import { selectRoute, setHoveredRoute, usePlanStore } from '../../store/planStore'
import { RISK_HEX } from '../../lib/risk/levels'
import { LevelChip, LevelSwatch, NoTravelIcon } from '../../ui/LevelChip'
import { MileageBar } from './MileageBar'

export interface RouteCardProps {
  route: MapRoute
  /** The scored route; `null` while weather is still streaming. */
  scored: PlanRoute | null
  interval: IntervalMi
  recommended: boolean
  applyHos: boolean
  originTz: string | null
}

function durationText(route: MapRoute, applyHos: boolean): string {
  const { duration_s: total, hos_stop_s: stopS } = route.summary
  if (!applyHos) return formatDuration(total)
  if (stopS <= 0) return `${formatDuration(total)}, no HOS stops`
  const n = route.stops.length
  return `${formatDuration(total)} incl. ${formatDuration(stopS)} HOS (${n} stop${n === 1 ? '' : 's'})`
}

/**
 * One route: identity, distance, duration, arrival, and the risk summary for the active interval.
 * The whole card is one toggle button; hover and focus highlight the route on the map.
 */
export function RouteCard({
  route,
  scored,
  interval,
  recommended,
  applyHos,
  originTz,
}: RouteCardProps) {
  // Per-card booleans: hovering one card re-renders only the cards whose flag changed.
  const selected = usePlanStore((s) => s.selectedRouteId === route.id)
  const hovered = usePlanStore((s) => s.hoveredRouteId === route.id)
  const aggregates = scored?.intervals[interval].aggregates ?? null
  const ntMi = aggregates?.miles_by_level.NO_TRAVEL ?? 0
  const severeMi = aggregates?.miles_by_level.SEVERE ?? 0

  return (
    <button
      type="button"
      aria-pressed={selected}
      aria-label={`${route.label}${recommended ? ', recommended' : ''}`}
      aria-describedby={`route-${route.id}-details`}
      data-testid={`route-card-${route.id}`}
      onClick={() => selectRoute(route.id)}
      onMouseEnter={() => setHoveredRoute(route.id)}
      onMouseLeave={() => setHoveredRoute(null)}
      onFocus={() => setHoveredRoute(route.id)}
      onBlur={() => setHoveredRoute(null)}
      className={`block w-full rounded-lg border bg-surface p-3 text-left text-sm shadow-sm transition-[border-color,box-shadow] focus-visible:ring-2 focus-visible:ring-accent focus-visible:ring-offset-2 focus-visible:ring-offset-surface focus-visible:outline-none ${
        selected
          ? 'border-accent ring-1 ring-accent'
          : hovered
            ? 'border-line-strong shadow-md'
            : 'border-line'
      }`}
    >
      <span className="flex items-center gap-2">
        <span
          aria-hidden
          className="flex size-6 shrink-0 items-center justify-center rounded-md text-xs font-bold text-white"
          style={{ backgroundColor: route.hex }}
        >
          {route.id}
        </span>
        <span className="font-semibold text-ink">{route.label}</span>
        {route.source === 'via_point' && (
          <span className="text-xs text-ink-3" title="Generated by routing through a via point">
            detour
          </span>
        )}
        {recommended && (
          <span className="ml-auto inline-flex items-center gap-1 rounded-full bg-accent px-2 py-0.5 text-xs font-semibold text-accent-ink">
            <svg viewBox="0 0 12 12" aria-hidden className="size-3">
              <path
                d="M2.5 6.5l2.2 2.2 4.8-5"
                fill="none"
                stroke="currentColor"
                strokeWidth="1.8"
              />
            </svg>
            Recommended
          </span>
        )}
      </span>

      <span id={`route-${route.id}-details`} className="block">
        <span className="mt-2 grid grid-cols-[auto_1fr] gap-x-3 gap-y-0.5 text-xs text-ink-2">
          <span className="text-ink-3">Distance</span>
          <span className="tabular-nums">{formatMiles(route.distanceMi)}</span>
          <span className="text-ink-3">Duration</span>
          <span className="tabular-nums">{durationText(route, applyHos)}</span>
          <span className="text-ink-3">Arrives</span>
          <span className="tabular-nums">{formatTime(route.summary.arrival_utc, originTz)}</span>
        </span>

        {aggregates ? (
          <>
            {(ntMi > 0 || severeMi > 0) && (
              <span className="mt-2 flex flex-wrap gap-1.5">
                {ntMi > 0 && (
                  <span
                    className="inline-flex items-center gap-1 rounded-md border px-1.5 py-0.5 text-xs font-semibold text-ink"
                    style={{ borderColor: RISK_HEX.NO_TRAVEL }}
                  >
                    <NoTravelIcon className="size-3" />
                    No Travel {formatMiles(ntMi)}
                  </span>
                )}
                {severeMi > 0 && (
                  <span className="inline-flex items-center gap-1 rounded-md border border-line-strong px-1.5 py-0.5 text-xs font-semibold text-ink">
                    <LevelSwatch level="SEVERE" className="size-2" />
                    Severe {formatMiles(severeMi)}
                  </span>
                )}
              </span>
            )}
            <span className="mt-2.5 block">
              <MileageBar milesByLevel={aggregates.miles_by_level} />
            </span>
            <span className="mt-2 flex items-center justify-between gap-2 text-xs text-ink-2">
              <span>
                Avg risk{' '}
                <span className="font-semibold text-ink tabular-nums">
                  {formatAvgRisk(aggregates.avg_risk)}
                </span>
                <span className="text-ink-3"> / 4</span>
              </span>
              <span className="inline-flex items-center gap-1.5">
                <span className="text-ink-3">Worst</span>
                <LevelChip level={aggregates.max_level} />
              </span>
            </span>
          </>
        ) : (
          <span className="mt-3 block space-y-2" aria-hidden>
            <span className="block h-2.5 animate-pulse rounded-full bg-surface-2" />
            <span className="block h-3 w-2/3 animate-pulse rounded bg-surface-2" />
          </span>
        )}
      </span>
    </button>
  )
}

